/// The reference with key `key`.
pub fn find(key: &str) -> Option<&'static Ref> {
    REFS.iter().find(|r| r.key == key)
}

/// All references sorted by their full citation (author, year).
pub fn sorted() -> Vec<&'static Ref> {
    let mut v: Vec<&Ref> = REFS.iter().collect();
    v.sort_by_key(|r| sort_key(r.full));
    v
}

/// Initial of the sort key (headings of the reference list).
pub fn letter(r: &Ref) -> char {
    sort_key(r.full).chars().next().unwrap_or(' ').to_ascii_uppercase()
}

/// Sort key: the citation without diacritics and case, so that "Šimůnek" sorts with "S" and "van Genuchten" with "v".
fn sort_key(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            'Š' | 'š' => 's',
            'ů' | 'ú' => 'u',
            'Å' | 'å' => 'a',
            'é' | 'è' => 'e',
            'í' => 'i',
            'ö' | 'ø' => 'o',
            'ü' => 'u',
            c => c.to_ascii_lowercase(),
        })
        .collect()
}

