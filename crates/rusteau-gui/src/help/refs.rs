//! Literature: the scientific sources of the equations and methods of Rusteau-1D (the HYDRUS-1D code it follows and
//! the additions of Rusteau). Topics cite them with `[@key]`; the topic "References" lists all of them.

/// One reference. `full` uses the inline markup of the help topics (journal names in `*…*`).
pub struct Ref {
    pub key: &'static str,
    /// Short form used in the text, e.g. "van Genuchten (1980)"
    pub short: &'static str,
    pub full: &'static str,
    pub doi: Option<&'static str>,
    pub url: Option<&'static str>,
    /// What Rusteau-1D bases on it
    pub used_for: &'static str,
}

macro_rules! r {
    ($key:expr, $short:expr, $full:expr, doi: $doi:expr, $used:expr) => {
        Ref { key: $key, short: $short, full: $full, doi: Some($doi), url: None, used_for: $used }
    };
    ($key:expr, $short:expr, $full:expr, url: $url:expr, $used:expr) => {
        Ref { key: $key, short: $short, full: $full, doi: None, url: Some($url), used_for: $used }
    };
    ($key:expr, $short:expr, $full:expr, $used:expr) => {
        Ref { key: $key, short: $short, full: $full, doi: None, url: None, used_for: $used }
    };
}

